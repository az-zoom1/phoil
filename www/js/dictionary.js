  function cleanToken(raw) {
    return String(raw || "")
      .toLowerCase()
      .replace(/^[^a-z]+|[^a-z]+$/g, "");
  }

  function transliterateApprox(word) {
    const map = {
      sh: "ش", ch: "تش", th: "ث", ph: "ف", oo: "و", ee: "ي",
      a: "ا", b: "ب", c: "ك", d: "د", e: "ي", f: "ف", g: "غ",
      h: "هـ", i: "ي", j: "ج", k: "ك", l: "ل", m: "م", n: "ن",
      o: "و", p: "ب", q: "ك", r: "ر", s: "س", t: "ت", u: "و",
      v: "ف", w: "و", x: "كس", y: "ي", z: "ز"
    };
    let out = "";
    for (let i = 0; i < word.length; i++) {
      const two = word.slice(i, i + 2);
      if (map[two]) {
        out += map[two];
        i++;
      } else {
        out += map[word[i]] || word[i];
      }
    }
    return out;
  }

  function lookup(rawWord) {
    const clean = cleanToken(rawWord);
    if (!clean) return null;

    if (DICT[clean]) {
      return {
        word: clean,
        meaningAr: DICT[clean][0],
        ipa: DICT[clean][1],
        arabicPhonetic: DICT[clean][2]
      };
    }

    // Morphological stem fallback
    const candidates = [
      clean.replace(/'s$|'re$|'m$|'ve$|'ll$/, ""),
      clean.replace(/ies$/, "y"),
      clean.replace(/es$/, ""),
      clean.replace(/s$/, ""),
      clean.replace(/ed$/, ""),
      clean.replace(/ing$/, ""),
      clean.replace(/ing$/, "e"),
      clean.replace(/ly$/, "")
    ];

    for (const stem of candidates) {
      if (stem && DICT[stem]) {
        return {
          word: clean,
          meaningAr: DICT[stem][0],
          ipa: DICT[stem][1],
          arabicPhonetic: DICT[stem][2]
        };
      }
    }

    return {
      word: clean,
      meaningAr: "كلمة إنجليزية (اسأل فويل 'ما معنى هذه؟' للشرح الموسّع)",
      ipa: "/" + clean + "/",
      arabicPhonetic: transliterateApprox(clean)
    };
  }

